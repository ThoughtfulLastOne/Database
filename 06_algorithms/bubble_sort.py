numbers = [64, 34, 25, 12, 22, 11, 90]

print("Исходный список:", numbers)

n = len(numbers)

# Проходим по всем элементам списка
for i in range(n):
    swapped = False  # Флаг: были ли обмены на этом проходе
    
    # После каждого прохода наибольший элемент будет на своем месте,
    # поэтому можно игнорировать последний элемент на каждом новом шаге.
    for j in range(0, n - i - 1):
        if numbers[j] > numbers[j + 1]:
            # Меняем местами элементы, если они в неправильном порядке
            numbers[j], numbers[j + 1] = numbers[j + 1], numbers[j]
            swapped = True  # Запоминаем, что обмен был
    
    # Печатаем список после каждого прохода, чтобы увидеть процесс
    print(f"После {i + 1}-го прохода: {numbers}")
    
    # Если за весь проход не было обменов — массив уже отсортирован
    if not swapped:
        print("Массив уже отсортирован, досрочный выход.")
        break

print("Отсортированный список:", numbers)


'''1. Внешний цикл: Проходит по списку и повторяет процесс сортировки столько раз,
сколько элементов в списке. После каждого прохода самый большой элемент 
"всплывает" на своё место, поэтому количество элементов для сортировки 
сокращается.

2. Внутренний цикл: Сравнивает соседние элементы и меняет их местами, если 
они в неправильном порядке. После одного полного прохода последний элемент 
оказывается на своём месте.

3. Печать состояния списка: После каждого прохода по списку, мы выводим его 
состояние, чтобы увидеть, как элементы "всплывают" на свои места.

4. Если не срабатывает флаг swapped (замен не было) - массив отсортирован, цикл 
прерывается.'''