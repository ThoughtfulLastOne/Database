numbers = [64, 34, 25, 12, 22, 11, 90]

print("Исходный список:", numbers)

# Проходим по списку с 1-го элемента
for i in range(1, len(numbers)):
    key = numbers[i]  # Текущий элемент
    j = i - 1
    
    # Перемещаем элементы, которые больше текущего, на одну позицию вперед
    while j >= 0 and numbers[j] > key:
        numbers[j + 1] = numbers[j]
        j -= 1
    
    # Вставляем текущий элемент на его правильное место
    numbers[j + 1] = key

    # Печатаем список после каждого прохода
    print(f"После {i}-го прохода: {numbers}")

print("Отсортированный список:", numbers)

                  
'''1. Внешний цикл начинается со второго элемента (индекс 1).  
   Первый элемент (индекс 0) считается уже отсортированной частью.

2. Текущий элемент сохраняется в отдельную переменную (ключ).

3. Внутренний цикл (while) сравнивает ключ с элементами из отсортированной части,  
   расположенными слева.  
   Если очередной элемент больше ключа, он сдвигается на одну позицию вправо,  
   освобождая место для вставки.

4. После завершения сдвигов ключ вставляется на освободившуюся позицию.

5. После каждой вставки выводится текущее состояние списка,  
   чтобы можно было наблюдать рост отсортированной части.

6. Алгоритм завершается, когда все элементы будут обработаны.'''