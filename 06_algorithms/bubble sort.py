numbers = [64, 34, 25, 12, 22, 11, 90]

print("Исходный список:", numbers)

n = len(numbers)

# Проходим по всем элементам списка
for i in range(n):
    # После каждого прохода наибольший элемент будет на своем месте,
    # поэтому можно игнорировать последний элемент на каждом новом шаге.
    for j in range(0, n-i-1):
        if numbers[j] > numbers[j+1]:
            # Меняем местами элементы, если они в неправильном порядке
            numbers[j], numbers[j+1] = numbers[j+1], numbers[j]
    
    # Печатаем список после каждого прохода, чтобы увидеть процесс
    print(f"После {i+1}-го прохода: {numbers}")

print("Отсортированный список:", numbers)