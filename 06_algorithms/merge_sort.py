numbers = [64, 34, 25, 12, 22, 11, 90]
print("Исходный список:", numbers)

# Разбиваем список на отдельные элементы
sorted_sublists = [[num] for num in numbers]

# Пока есть хотя бы две подгруппы, продолжаем объединять их
while len(sorted_sublists) > 1:
    merged_sublists = []  # Новый список для хранения объединенных подгрупп

    # Объединяем пары подгрупп
    i = 0
    while i < len(sorted_sublists) - 1:
        left = sorted_sublists[i]  # Левая половина
        right = sorted_sublists[i + 1]  # Правая половина
        merged = []  # Итоговый объединенный список

        # Индексы для прохода по спискам left и right
        li = ri = 0

        # Слияние двух отсортированных подгрупп
        while li < len(left) and ri < len(right):
            if left[li] < right[ri]:
                merged.append(left[li])
                li += 1
            else:
                merged.append(right[ri])
                ri += 1

        # Добавляем оставшиеся элементы из левой подгруппы
        while li < len(left):
            merged.append(left[li])
            li += 1

        # Добавляем оставшиеся элементы из правой подгруппы
        while ri < len(right):
            merged.append(right[ri])
            ri += 1

        merged_sublists.append(merged)  # Добавляем объединенный список в новый массив
        i += 2  # Переход к следующей паре подгрупп

    # Если осталась одна нечетная подгруппа, добавляем её в конец
    if len(sorted_sublists) % 2 == 1:
        merged_sublists.append(sorted_sublists[-1])

    sorted_sublists = merged_sublists  # Обновляем подгруппы

# Итоговый отсортированный список
numbers = sorted_sublists[0]
print("Отсортированный список:", numbers)

"""
1. Исходный список разбивается на подсписки из одного элемента.
   Каждый такой подсписок считается отсортированным.

2. Подсписки попарно сливаются в отсортированные подсписки большего размера.
   Сравниваются первые элементы двух подсписков, меньший переносится в результат,
   затем процесс повторяется, пока один из подсписков не закончится.

3. Оставшиеся элементы из более длинного подсписка добавляются в конец результата.

4. Процесс слияния повторяется до тех пор, пока не останется один отсортированный список.

5. После каждого шага слияния состояние списка может быть выведено для наблюдения.
"""