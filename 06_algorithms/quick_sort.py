numbers = [64, 34, 25, 12, 22, 11, 90]

print("Исходный список:", numbers)

# Исходный список и стэк
stack = [(0, len(numbers) - 1)]

while stack:
    left, right = stack.pop()

    if left < right:
        pivot = numbers[right]  # Опорный элемент
        i = left - 1

        # Разделяем элементы относительно опорного
        for j in range(left, right):
            if numbers[j] < pivot:
                i += 1
                numbers[i], numbers[j] = numbers[j], numbers[i]

        # Перемещаем опорный элемент на своё место
        numbers[i + 1], numbers[right] = numbers[right], numbers[i + 1]

        # Добавляем подсписки в стек для дальнейшей сортировки
        stack.append((left, i))
        stack.append((i + 2, right))

print("Отсортированный список:", numbers)

